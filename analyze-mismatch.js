#!/usr/bin/env node
/**
 * Deep analysis of broken link patterns
 */

const fs = require('fs');
const path = require('path');

const auditResults = JSON.parse(fs.readFileSync('./link-audit-results.json', 'utf8'));
const brokenLinks = auditResults.results.filter(r => !r.exists);

console.log('='.repeat(100));
console.log('ROOT CAUSE ANALYSIS - BROKEN "READ ISSUE" LINKS');
console.log('='.repeat(100));
console.log();

// Analyze the pattern
console.log('BROKEN LINKS SUMMARY:');
console.log('-'.repeat(100));

brokenLinks.forEach((link, i) => {
    console.log(`\n${i + 1}. Title: "${link.title}"`);
    console.log(`   Current Href: ${link.href}`);
    console.log(`   Date: ${link.date}`);
    
    // Analyze the slug pattern
    const slug = path.basename(link.href, '.html');
    console.log(`   Slug: ${slug}`);
    
    // Check for truncation (common issue with auto-generated slugs)
    if (slug.endsWith('-') || slug.endsWith('.') || slug.length < 30) {
        console.log(`   ⚠️  WARNING: Slug appears truncated or incomplete`);
    }
});

console.log();
console.log('='.repeat(100));
console.log('PATTERN ANALYSIS');
console.log('='.repeat(100));
console.log();

// Check if these are auto-generated cards with malformed data
const autoGeneratedPattern = brokenLinks.filter(l => 
    l.title.includes('PUBLICATION:') || 
    l.date.match(/^\d{4}-\d{2}-\d{2}$/) ||  // ISO date format
    l.href.includes('/arlington/articles/') && path.basename(l.href, '.html').length < 35
);

console.log(`Auto-generated cards detected: ${autoGeneratedPattern.length}/${brokenLinks.length}`);
console.log();

// Root cause determination
console.log('ROOT CAUSE DETERMINATION:');
console.log('-'.repeat(100));
console.log();
console.log('OBSERVATION: All 8 broken links share these characteristics:');
console.log('  1. They have ISO date format (2026-06-29) vs natural format (June 29, 2026)');
console.log('  2. The card HTML uses <div> instead of <article> tags');
console.log('  3. The slugs appear truncated or auto-generated');
console.log('  4. The title/description contains "PUBLICATION: Arlington Pulse" text');
console.log();
console.log('CONCLUSION: These are AUTO-GENERATED CARDS from an external source');
console.log('(likely Letterman AI article import or RSS feed) where:');
console.log('  - The card HTML was injected into index.html');
console.log('  - But the corresponding article files were NOT created');
console.log('  - OR the article files were created with DIFFERENT slugs');
console.log();

// Check if articles might exist with different slugs
console.log('CHECKING FOR SIMILAR ARTICLES:');
console.log('-'.repeat(100));
console.log();

const existingFiles = auditResults.existingFiles;

brokenLinks.forEach(link => {
    const titleWords = link.title
        .toLowerCase()
        .replace(/[^\w\s]/g, '')
        .split(' ')
        .filter(w => w.length > 3)
        .slice(0, 4);
    
    const similar = existingFiles.filter(f => {
        const fileWords = path.basename(f, '.html').toLowerCase().split('-');
        return titleWords.some(tw => fileWords.includes(tw));
    });
    
    if (similar.length > 0) {
        console.log(`\n"${link.title.substring(0, 40)}..."`);
        console.log(`  Broken: ${link.href}`);
        console.log(`  Similar files found:`);
        similar.forEach(s => console.log(`    - ${s}`));
    }
});

console.log();
console.log('='.repeat(100));
console.log('BUG CLASSIFICATION');
console.log('='.repeat(100));
console.log();
console.log('TYPE: Data/Content Mismatch (NOT template logic)');
console.log();
console.log('The bug is in the DATA layer, not the URL builder:');
console.log('  ✅ Template logic is CORRECT - it renders what\'s in the HTML');
console.log('  ❌ DATA is INCONSISTENT - cards reference non-existent articles');
console.log();
console.log('SOURCE OF ISSUE:');
console.log('  - External content import (Letterman AI / RSS / Automation)');
console.log('  - Cards were added to index.html without verifying article existence');
console.log('  - Slug generation mismatch between card href and actual file creation');
console.log();

// Proposed fix
console.log('='.repeat(100));
console.log('PROPOSED MINIMAL FIX');
console.log('='.repeat(100));
console.log();
console.log('OPTION 1: Remove broken cards (QUICK FIX)');
console.log('  - Delete the 8 auto-generated <div class="issue-card"> entries from index.html');
console.log('  - Only keep manually created <article class="issue-card"> entries');
console.log('  - Pros: Immediate fix, clean codebase');
console.log('  - Cons: Loses content that might have been intended');
console.log();
console.log('OPTION 2: Create missing article files (CONTENT FIX)');
console.log('  - Generate the 8 missing article HTML files with proper content');
console.log('  - Match the slugs exactly as referenced in the cards');
console.log('  - Pros: Preserves all content');
console.log('  - Cons: Requires content creation, more time');
console.log();
console.log('OPTION 3: Fix slug mapping (DATA FIX)');
console.log('  - Update hrefs in index.html to point to existing similar articles');
console.log('  - Or update existing article slugs to match card hrefs');
console.log('  - Pros: Maintains link integrity');
console.log('  - Cons: Risk of breaking other references');
console.log();
console.log('RECOMMENDATION: Option 1 (Remove broken cards) + Option 2 (Create articles later)');
console.log('  - Immediate: Remove broken cards to fix 404s');
console.log('  - Future: Re-import content properly with article file creation');
